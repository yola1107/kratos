package main

import (
	"fmt"
	"strconv"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/descriptorpb"
)

// generateFile generates a _gnet.pb.go file containing kratos gnet service definitions.
func generateFile(gen *protogen.Plugin, file *protogen.File) *protogen.GeneratedFile {
	if len(file.Services) == 0 {
		return nil
	}
	filename := file.GeneratedFilenamePrefix + "_gnet.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	generateFileHeader(gen, file, g)
	generateImports(gen, file, g)

	for _, service := range file.Services {
		genService(gen, file, g, service)
	}

	return g
}

func generateFileHeader(gen *protogen.Plugin, file *protogen.File, g *protogen.GeneratedFile) {
	g.P("// Code generated by protoc-gen-go-gnet. DO NOT EDIT.")
	g.P("// versions:")
	g.P(fmt.Sprintf("// - protoc-gen-go-gnet %s", release))
	g.P("// - protoc            ", protocVersion(gen))
	if file.Proto.GetOptions().GetDeprecated() {
		g.P("// ", file.Desc.Path(), " is a deprecated file.")
	} else {
		g.P("// source: ", file.Desc.Path())
	}
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
}

func generateImports(gen *protogen.Plugin, file *protogen.File, g *protogen.GeneratedFile) {
	if len(file.Services) == 0 {
		return
	}
	g.P("// This is a compile-time assertion to ensure that this generated file")
	g.P("// is compatible with the kratos package it is being compiled against.")

	g.P(`import (`)
	g.P(`\t"context"`)
	g.P()
	g.P(`\tgnet "github.com/yola1107/kratos/v2/transport/gnet"`)
	g.P()
	g.P(`\t"google.golang.org/grpc/codes"`)
	g.P(`\t"google.golang.org/grpc/status"`)
	g.P(`\t"google.golang.org/protobuf/proto"`)
	g.P(`)`)
	g.P()
}

func genService(gen *protogen.Plugin, file *protogen.File, g *protogen.GeneratedFile, service *protogen.Service) {
	if service.Desc.Options().(*descriptorpb.ServiceOptions).GetDeprecated() {
		g.P("//")
		g.P(deprecationComment)
	}

	var (
		serviceName    = service.GoName
		serviceDescVar = fmt.Sprintf("%s_GNET_ServiceDesc", serviceName)
		fullServName   = fmt.Sprintf("%s.%s", file.Desc.Package(), serviceName)
	)

	generateGNETInterface(g, serviceName, service)

	g.P("func Register", serviceName, "GNETServer(s *gnet.Server, srv ", serviceName, "GNETServer) {")
	g.P("\ts.RegisterService(&", serviceDescVar, ", srv)")
	g.P("}")
	g.P()

	var handlerNames []string
	for _, method := range service.Methods {
		hname := generateServerMethod(g, serviceName, fullServName, method)
		handlerNames = append(handlerNames, hname)
	}

	gameCommand := make(map[string]string)
	for _, enum := range file.Enums {
		if enum.Desc.Name() != "GameCommand" {
			continue
		}
		for _, v := range enum.Values {
			gameCommand[string(v.Desc.Name())] = fmt.Sprintf("%d", v.Desc.Number())
		}
	}

	g.P(`var `, serviceDescVar, ` = gnet.ServiceDesc{`)
	g.P(`\tServiceName: `, strconv.Quote(fullServName), `,`)
	g.P(`\tHandlerType: (*`, serviceName, `GNETServer)(nil),`)
	g.P(`\tMethods: []gnet.MethodDesc{`)
	for i, method := range service.Methods {
		g.P(`\t\t{`)
		g.P(`\t\t\tMethodName: `, strconv.Quote(method.GoName), `,`)
		g.P(`\t\t\tHandler: `, handlerNames[i], `,`)
		g.P(`\t\t\tOps: `, gameCommand[method.GoName], `,`)
		g.P(`\t\t},`)
	}
	g.P(`\t},`)
	g.P(`}`)
}

func generateGNETInterface(g *protogen.GeneratedFile, serviceName string, service *protogen.Service) {
	g.P("// ", serviceName, "GNETServer is the server API for ", serviceName, " service.")
	g.P("type ", serviceName, "GNETServer interface {")
	for _, method := range service.Methods {
		if method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer() {
			continue
		}
		g.P("\t", method.GoName, "(context.Context, *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error)")
	}
	g.P(`}`)
	g.P()
}

func generateServerMethod(g *protogen.GeneratedFile, servName, fullServName string, method *protogen.Method) string {
	methName := method.GoName
	hname := fmt.Sprintf("_%s_%s_GNET_Handler", servName, methName)
	inputType := method.Input.Desc.Name()

	g.P(`func `, hname, `(srv interface{}, ctx context.Context, data []byte, interceptor gnet.UnaryServerInterceptor) ([]byte, error) {`)
	g.P(`\tin := new(`, inputType, `)`)
	g.P(`\tif err := proto.Unmarshal(data, in); err != nil {`)
	g.P(`\t\treturn nil, err`)
	g.P(`\t}`)
	g.P(`\tdoFunc := func(ctx context.Context, req *`, inputType, `) ([]byte, error) {`)
	g.P(`\t\tresp, err := srv.(`, servName, `GNETServer).`, methName, `(ctx, req)`)
	g.P(`\t\tif err != nil || resp == nil {`)
	g.P(`\t\t\treturn nil, err`)
	g.P(`\t\t}`)
	g.P(`\t\treturn proto.Marshal(resp)`)
	g.P(`\t}`)
	g.P(`\tif interceptor == nil {`)
	g.P(`\t\treturn doFunc(ctx, in)`)
	g.P(`\t}`)
	g.P(`\tinfo := &gnet.UnaryServerInfo{`)
	g.P(`\t\tServer:     srv,`)
	g.P(`\t\tFullMethod: `, strconv.Quote(fmt.Sprintf("/%s/%s", fullServName, methName)), `,`)
	g.P(`\t}`)
	g.P(`\thandler := func(ctx context.Context, req interface{}) ([]byte, error) {`)
	g.P(`\t\tr, ok := req.(*`, inputType, `)`)
	g.P(`\t\tif !ok {`)
	g.P(`\t\t\treturn nil, status.Errorf(codes.InvalidArgument, "Invalid Request Argument, expect: *`, inputType, `, Not: %T", req)`)
	g.P(`\t\t}`)
	g.P(`\t\treturn doFunc(ctx, r)`)
	g.P(`\t}`)
	g.P(`\treturn interceptor(ctx, in, info, handler)`)
	g.P(`}`)
	g.P()

	return hname
}

func protocVersion(gen *protogen.Plugin) string {
	v := gen.Request.GetCompilerVersion()
	if v == nil {
		return "(unknown)"
	}
	return fmt.Sprintf("v%d.%d.%d", v.GetMajor(), v.GetMinor(), v.GetPatch())
}

const deprecationComment = "// Deprecated: Do not use."
